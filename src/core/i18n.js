export function init(initial) {
  if (initial) lang = initial;
}

export function t(key) {
  const val = (dict[lang] && dict[lang][key]) || dict[DEFAULT][key];
  if (val == null && typeof console !== 'undefined') console.warn(`Missing translation key: ${key}`);
  return val || key;
}

export function getLanguage() { return lang; }

export function setLanguage(l) {
  if (!l || lang === l) return;
  lang = l;
  // notify subscribers
  subs.forEach(cb => {
    try { cb(lang); } catch (e) { console.warn('i18n cb', e); }
  });
  document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
}

export function subscribe(cb) { subs.add(cb); return () => subs.delete(cb); }

export default { init, t, getLanguage, setLanguage, subscribe };
